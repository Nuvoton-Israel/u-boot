uint8_t *MASS_STORAGE_DISK;

static int ums_mem_read_sector(struct ums *ums_dev,
			   ulong start, lbaint_t blkcnt, void *buf)
{
	lbaint_t blkstart = START_ADDR + (start *  BLOCK_SIZE ) + ums_dev->start_sector;
	memcpy(buf, (uint8_t*)blkstart, blkcnt * BLOCK_SIZE);

	return blkcnt;
}

static int ums_mem_write_sector(struct ums *ums_dev,
			    ulong start, lbaint_t blkcnt, const void *buf)
{
	lbaint_t blkstart = START_ADDR + (start *  BLOCK_SIZE ) + ums_dev->start_sector;
	memcpy((uint8_t*)blkstart, buf, blkcnt * BLOCK_SIZE);

	return blkcnt;
}

static struct ums *ums;
static int ums_count;

static void ums_fini(void)
{
	int i;

	for (i = 0; i < ums_count; i++)
		free((void *)ums[i].name);
	free(ums);
	ums = NULL;
	ums_count = 0;
}

#define UMS_NAME_LEN 16


static int ums_init(const char *devtype, const char *devnums_part_str)
{
	char *name;
	int ret = -1;
	struct ums *ums_new;

	ums_new = realloc(ums, (ums_count + 1) * sizeof(*ums));
	if (!ums_new)
		goto cleanup;
	ums = ums_new;

	MASS_STORAGE_DISK = (uint8_t *)START_ADDR;
#if 1
	   /* Format the "disk" */
	   memcpy(MASS_STORAGE_DISK, BOOT_SECTOR_AREA, 512);
	#if 0 // ohad - testing why linux thinks partition 1 is larger than the disk
	   memcpy(MASS_STORAGE_DISK + 512, FAT16_SPECIAL_BYTES, 3);
	   memcpy(MASS_STORAGE_DISK + 512*4, FAT16_SPECIAL_BYTES, 3);
	#endif
		  /* Nuvoton - Yarkon Windows format SL!!! */
	   memcpy(MASS_STORAGE_DISK + 512*17, FAT16_WINDOWS_BYTES, 512);
	   memcpy(MASS_STORAGE_DISK + 512*19, FAT16_WINDOWS_SPECIAL_BYTES, 4);
#endif
	ums[ums_count].start_sector = 0;
	ums[ums_count].num_sectors = 0x40000;

	ums[ums_count].read_sector = ums_mem_read_sector;
	ums[ums_count].write_sector = ums_mem_write_sector;

	name = malloc(UMS_NAME_LEN);
	if (!name)
		goto cleanup;
	snprintf(name, UMS_NAME_LEN, "UMS mem disk %d", ums_count);
	ums[ums_count].name = name;
	ums[ums_count].block_dev.hwpart = 0;
	ums[ums_count].block_dev.devnum = 0;
	ums[ums_count].block_dev.blksz = 512;

	printf("UMS: LUN %d, dev %s %d, hwpart %d, sector %#x, count %#x\n",
	       ums_count, devtype, ums[ums_count].block_dev.devnum,
	       ums[ums_count].block_dev.hwpart,
	       ums[ums_count].start_sector,
	       ums[ums_count].num_sectors);

	ums_count = 1;

	ret = 0;

cleanup:

	if (ret < 0)
		ums_fini();

	return ret;
}

